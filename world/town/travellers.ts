export function randomName(random = Math.random): string {
  const pick = <T>(list: readonly T[]) => list[Math.floor(random() * list.length)]
  const name = `${pick(EPITHET)}${pick(FIRST)}`
  return name.length <= 16 ? name : pick(FIRST)
}

